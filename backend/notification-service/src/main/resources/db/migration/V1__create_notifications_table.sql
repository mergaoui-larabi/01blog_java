CREATE TABLE
    notifications (
        id UUID PRIMARY KEY,
        -- User receiving the notification
        recipient_id UUID NOT NULL,
        -- User who triggered the event
        actor_id UUID NOT NULL,
        type VARCHAR(30) NOT NULL DEFAULT 'NEW_POST',
        resource_id UUID,
        message TEXT,
        read BOOLEAN NOT NULL DEFAULT false,
        read_at TIMESTAMPTZ,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT chk_notification_different_users CHECK (recipient_id <> actor_id)
    );

-- Retrieve a user's notifications, newest first
CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_id, created_at DESC, id DESC);

-- Retrieve unread notifications efficiently
CREATE INDEX idx_notifications_unread ON notifications (recipient_id, created_at DESC)
WHERE
    read_at IS NULL;

-- Retrieve notifications generated by a particular user
CREATE INDEX idx_notifications_actor ON notifications (actor_id);